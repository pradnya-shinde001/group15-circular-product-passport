-- One SQLite database shared by all four subsystems.
-- Created automatically by database/connection.py (init_db). Every statement is safe to run again.

-- Subsystem 1: Passport, QR code and web UI -------------------------------

CREATE TABLE IF NOT EXISTS users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    email         TEXT NOT NULL UNIQUE,
    role          TEXT NOT NULL CHECK (role IN ('admin', 'manufacturer', 'recycler', 'consumer')),
    password_hash TEXT NOT NULL              -- salted PBKDF2 hash from the User class, never the password
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,                       -- SHA-256 of the login token, never the token itself
    user_id    INTEGER NOT NULL REFERENCES users (id),
    expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS products (
    uuid                TEXT PRIMARY KEY,    -- generated by the Product class, never changes
    name                TEXT NOT NULL,
    model               TEXT NOT NULL DEFAULT '',
    category            TEXT NOT NULL,
    lifespan_years      REAL NOT NULL CHECK (lifespan_years > 0),
    spare_parts_percent INTEGER NOT NULL DEFAULT 0 CHECK (spare_parts_percent BETWEEN 0 AND 100),
    condition           TEXT NOT NULL DEFAULT 'Good',
    owner_id            INTEGER REFERENCES users (id),
    public_url          TEXT NOT NULL,       -- the address the QR code opens
    created_at          TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS material_components (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    product_uuid TEXT NOT NULL REFERENCES products (uuid),
    material     TEXT NOT NULL,
    percent      REAL NOT NULL CHECK (percent > 0 AND percent <= 100),
    recycled     INTEGER NOT NULL DEFAULT 0,  -- 0 or 1
    recyclable   INTEGER NOT NULL DEFAULT 0,  -- 0 or 1
    hazard       INTEGER NOT NULL DEFAULT 0   -- 0 or 1
);

-- Subsystem 2: Event ledger ------------------------------------------------

CREATE TABLE IF NOT EXISTS lifecycle_events (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    product_uuid  TEXT NOT NULL REFERENCES products (uuid),
    event_type    TEXT NOT NULL,
    timestamp     TEXT NOT NULL,
    actor_email   TEXT NOT NULL,
    details       TEXT NOT NULL,              -- JSON
    previous_hash TEXT NOT NULL,
    event_hash    TEXT NOT NULL,
    UNIQUE (product_uuid, previous_hash)      -- the chain can never fork
);

-- Stored events are append-only: the database itself refuses to change or remove one.
CREATE TRIGGER IF NOT EXISTS events_no_update BEFORE UPDATE ON lifecycle_events
BEGIN SELECT RAISE(ABORT, 'Lifecycle events are append-only.'); END;

CREATE TRIGGER IF NOT EXISTS events_no_delete BEFORE DELETE ON lifecycle_events
BEGIN SELECT RAISE(ABORT, 'Lifecycle events are append-only.'); END;

-- Subsystem 3: Circularity score engine ------------------------------------

CREATE TABLE IF NOT EXISTS circularity_scores (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    product_uuid TEXT NOT NULL REFERENCES products (uuid),
    total        REAL NOT NULL,
    grade        TEXT NOT NULL,
    sub_scores   TEXT NOT NULL,               -- JSON list of the five sub-scores
    missing      TEXT NOT NULL DEFAULT '[]',  -- JSON list of missing data
    reason       TEXT NOT NULL,               -- what caused the calculation, e.g. "registered" or "event: repaired"
    computed_at  TEXT NOT NULL
);

-- Subsystem 4: AI engine ---------------------------------------------------

CREATE TABLE IF NOT EXISTS ai_predictions (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    product_uuid TEXT NOT NULL REFERENCES products (uuid),
    action       TEXT NOT NULL,
    reason       TEXT NOT NULL,
    source       TEXT NOT NULL,               -- "llm" or "rules"
    created_at   TEXT NOT NULL
);
